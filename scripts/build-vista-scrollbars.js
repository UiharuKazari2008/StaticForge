#!/usr/bin/env node
/**
 * Build public/css/vista-scrollbars.css from 7.css (public/css/7.scoped.css, khang-nd/7.css,
 * MIT): its Vista scrollbar rules (`.win7 .has-scrollbar::-webkit-scrollbar*`) become the
 * desktop's default scrollbar (Yukimi, 2026-10-12), together with the --w7-* variables they
 * read. The selector is wrapped in :where(), so any element with its own scrollbar styling
 * (custom scrollbars, hidden scrollbars, html) keeps it. Desktop mode only, not Classic.
 *
 *   node scripts/build-vista-scrollbars.js          # write the file
 *   node scripts/build-vista-scrollbars.js --check  # exit 1 when the file is out of date
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public/css/7.scoped.css');
const OUT = path.join(ROOT, 'public/css/vista-scrollbars.css');
const ROOT_SCOPE = 'body.desktop-mode:not(.windows-classic-theme)';
// Every native scrollbar on the desktop, except html (hidden), the JS custom-scrollbar
// containers (customScrollbar.js hides their native bar) and the title toolbars' thin bar.
// Specific enough to beat the app's own thin ::-webkit-scrollbar rules (Yukimi: Vista is the
// default unless a custom scrollbar is used); no !important, so display:none hiders still win.
const SCOPE = `${ROOT_SCOPE} :not(html):not(.has-custom-scrollbar):not(.scrollable-content):not(.form-section-scroll):not(.modal-window-title-toolbar)`;

function build() {
    const css = fs.readFileSync(SRC, 'utf8');
    // the variables live in several root blocks (.win7{…}, some at the start of a rule list)
    const vars = new Map();
    for (const block of css.matchAll(/\.win7\{([^}]*)\}/g)) {
        for (const decl of block[1].split(';')) {
            const i = decl.indexOf(':');
            if (i > 0 && decl.trim().startsWith('--w7-')) vars.set(decl.slice(0, i).trim(), decl.slice(i + 1).trim());
        }
    }
    if (!vars.size) throw new Error('7.css root variables not found');
    const rules = [];
    const used = new Set();
    const re = /([^{}]+)\{([^{}]*)\}/g;
    let m;
    while ((m = re.exec(css))) {
        const selectors = m[1].split(',').map((s) => s.trim()).filter((s) => s.startsWith('.win7 .has-scrollbar::-webkit-scrollbar'));
        if (!selectors.length) continue;
        const scoped = selectors.map((s) => `${SCOPE}${s.slice('.win7 .has-scrollbar'.length)}`);
        rules.push(`${scoped.join(',\n')} {\n    ${m[2].split(';').filter(Boolean).join(';\n    ')};\n}`);
        for (const v of m[2].match(/--w7-[a-z0-9_-]+/gi) || []) used.add(v);
    }
    // variables can reference other variables (e.g. --w7-sb-y uses --w7-el-bg)
    let grew = true;
    while (grew) {
        grew = false;
        for (const v of [...used]) {
            for (const dep of (vars.get(v) || '').match(/--w7-[a-z0-9_-]+/gi) || []) {
                if (!used.has(dep)) { used.add(dep); grew = true; }
            }
        }
    }
    const varBlock = [...used].sort().filter((v) => vars.has(v)).map((v) => `    ${v}: ${vars.get(v)};`).join('\n');
    return `/* Vista scrollbars: generated by scripts/build-vista-scrollbars.js from 7.css
   (public/css/7.scoped.css, khang-nd/7.css, MIT). Do not edit by hand.
   The desktop's scrollbar everywhere a custom scrollbar (customScrollbar.js) is not used. */

${ROOT_SCOPE} {
${varBlock}
}

/* scrollbar-width / scrollbar-color switch Chrome off ::-webkit-scrollbar: reset the places
   that set them to a thin bar, so they get the Vista scrollbar too */
${ROOT_SCOPE} :is(.explorer-grid-scroll, #fileSearchAutofill .character-autocomplete-list) {
    scrollbar-width: auto;
    scrollbar-color: auto;
}

${rules.join('\n\n')}
`;
}

const out = build();
if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) { console.error('vista-scrollbars.css is out of date'); process.exit(1); }
    console.log('vista-scrollbars.css is current');
} else {
    fs.writeFileSync(OUT, out);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${out.length} bytes)`);
}
