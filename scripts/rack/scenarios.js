'use strict';
// every node, then every dialog and wizard (each a screenshot; the screenshots are looked at by a person)
module.exports = async (x) => {
    const m = 'misaka';
    const N = (suffix) => `s:${m}${suffix}`;
    const dlg = async (name, action, arg, ms = 700) => { await x.act(action, arg); await x.wait(ms); await x.shot(name); };
    await x.wait(600);
    await x.shot('00-root');
    await x.select(N(''), 900); await x.shot('01-server-misaka');
    // Load History: stacked strips, the hover cursor, a longer range, then with the host off (off periods shaded)
    await x.ev(() => document.querySelector('#mmcConsole_rackManager [data-sec="rm-load"]').scrollIntoView()); await x.wait(500); await x.shot('01b-load-history-3h');
    await x.page.mouse.move(430, 330); await x.wait(300); await x.shot('01c-load-history-hover');
    await x.ev(() => { window.__mock.pushMetrics(); }); await x.wait(300);
    await x.ev(() => window.mmcConsole.get('rackManager').action('ld-range', '24h')); await x.wait(2500);
    await x.ev(() => document.querySelector('#mmcConsole_rackManager [data-sec="rm-load"]').scrollIntoView()); await x.wait(300); await x.shot('01d-load-history-24h');
    await x.ev(() => window.mmcConsole.get('rackManager').action('ld-range', '3h')); await x.wait(500);
    await x.ev(() => { window.__mock.shadeOff = true; }); await x.act('refresh'); await x.wait(4000);
    await x.ev(() => window.__mock.setPower('off')); await x.wait(700);
    await x.ev(() => document.querySelector('#mmcConsole_rackManager [data-sec="rm-load"]').scrollIntoView()); await x.wait(300); await x.shot('01e-load-history-host-off');
    await x.ev(() => { window.__mock.shadeOff = false; window.__mock.setPower('up'); }); await x.wait(500);
    await x.select('s:asuka', 600); await x.shot('02-server-asuka-not-deployed');
    await x.select('s:asuka:r:vms', 600); await x.shot('03-asuka-role-vms-not-deployed');
    // power on demand: the host goes off, a role page shows one state, Power On shows the POST progress
    await x.select(N(':r:vms'), 800);
    await x.ev(() => window.__mock.setPower('off')); await x.wait(500); await x.shot('04-role-host-off');
    await x.select(N(''), 500); await x.shot('05-server-host-off');
    await x.ev(() => window.__mock.setPower('powering-on')); await x.select(N(':r:vms'), 500); await x.shot('06-role-powering-on');
    await x.ev(() => window.__mock.setPower('booting')); await x.wait(300); await x.shot('07-role-booting');
    await x.ev(() => { window.__mock.setPower('up'); }); await x.wait(900);
    await x.select(N(':console'), 1500); await x.shot('10-console');
    await dlg('11-console-type-text', 'kvm-type'); await x.closeDialogs();
    await dlg('12-console-virtual-media', 'kvm-media', undefined, 1200); await x.closeDialogs();
    await dlg('13-console-screenshot', 'kvm-shot'); await x.closeDialogs();
    await x.select(N(':hardware'), 1800); await x.shot('20-hardware-health');
    await x.ev(() => window.mmcConsole.get('rackManager').action('hw-view', 'logs')); await x.wait(1200); await x.shot('21-hardware-logs');
    await x.ev(() => window.mmcConsole.get('rackManager').action('hw-view', 'ilo')); await x.wait(5000); await x.shot('22-hardware-ilo');
    await dlg('23-ilo-add-user', 'ilo-user-add'); await x.closeDialogs();
    await x.select(N(':power'), 1800); await x.shot('30-power');
    await x.ev(() => document.querySelector('#mmcConsole_rackManager .mmc-result .mmc-page-body').scrollTo(0, 900)); await x.wait(300); await x.shot('30b-power-lower');
    await dlg('30c-shutdown-task-dialog', 'host-off'); await x.closeDialogs();
    await dlg('31-power-hold-task-dialog', 'pw-op', 'hold'); await x.closeDialogs();
    await x.ev(() => window.mmcConsole.get('rackManager').action('pw-series', 'temp')); await x.wait(500); await x.shot('32-power-history-temps');
    await x.select(N(':roles'), 800); await x.shot('40-roles');
    await dlg('41-add-roles-wizard', 'addroles'); await x.closeDialogs();
    const role = async (id, ms = 900) => { await x.select(N(`:r:${id}`), ms); await x.shot(`5${id.length ? '' : ''}-role-${id}`); };
    await role('vms');
    await x.ev(() => { const c = window.mmcConsole.get('rackManager'); c.selectRow('ds-clone-1118'); }); await x.wait(400);
    await dlg('51-vm-selected-and-new-wizard', 'vm-new'); await x.closeDialogs();
    await dlg('52-vm-dsclone', 'vm-dsclone'); await x.closeDialogs();
    await dlg('53-vm-delete-task-dialog', 'vm-del'); await x.closeDialogs();
    await dlg('54-vm-snapshots', 'vm-snaps'); await x.closeDialogs();
    await dlg('55-vm-settings', 'vm-set'); await x.closeDialogs();
    await role('android');
    await x.ev(() => window.mmcConsole.get('rackManager').selectRow('aemu-fold-2')); await x.wait(300);
    await dlg('61-android-create-wizard', 'av-new'); await x.closeDialogs();
    await dlg('62-android-shell', 'av-shell'); await x.closeDialogs();
    await role('sandboxes');
    await dlg('71-sandbox-new', 'sb-new'); await x.closeDialogs();
    await role('containers');
    await x.ev(() => { window.__mock.info.roles.containers.installed = true; window.__mock.info.roles.builds.installed = true; });
    await x.act('refresh'); await x.wait(900); await x.shot('80-role-containers');
    await dlg('81-container-run-wizard', 'ct-run'); await x.closeDialogs();
    await dlg('82-container-prune', 'ct-prune'); await x.closeDialogs();
    await x.select(N(':r:builds'), 900); await x.shot('90-role-builds');
    await x.ev(() => window.mmcConsole.get('rackManager').selectRow('r:run-20261127-0')); await x.wait(900); await x.shot('91-builds-run-selected');
    await dlg('92-builds-new-pipeline', 'bd-new'); await x.closeDialogs();
    await x.select(N(':r:terminal'), 1500); await x.shot('A0-role-terminal');
    await x.select(N(':r:storage'), 900); await x.shot('B0-role-storage');
    await dlg('B1-storage-create-ramdisk', 'st-rdnew'); await x.closeDialogs();
    await dlg('B2-storage-create-volume', 'st-lvnew'); await x.closeDialogs();
    await x.select(N(':r:networking'), 900); await x.shot('C0-role-networking');
    await x.select(N(':r:services'), 900); await x.shot('D0-role-services');
    await x.ev(() => window.mmcConsole.get('rackManager').selectRow('u:rackd.service')); await x.wait(300);
    await dlg('D1-service-properties', 'sv-props'); await x.closeDialogs();
    await dlg('D2-define-rack-service', 'sv-def'); await x.closeDialogs();
    await x.select(N(':r:logs'), 900); await x.shot('E0-role-logs');
    await x.select(N(':r:updates'), 900); await x.shot('F0-role-updates');
    await x.select(N(':jobs'), 900); await x.shot('G0-jobs');
};
