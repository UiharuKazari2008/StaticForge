assert.ok(fm.liveSessionIds().size > 0);
// rcCandidates + finishedSessions (#1255)
const FULL = (c) => c.repeat(8) + '-1111-4111-8111-111111111111';
const lv = (c, status = 'idle', o = {}) => Object.assign({ id: FULL(c), status, origin: 'terminal', tmuxSession: '' }, o); // CLI 2.1.332: no tmux in the record
const wk = (id, state, c, full) => ({ id, state, session_id: full || FULL(c) });
const run = ({ names = [], live = [], rows = [], flight = () => false }) => {
    const { candidates, itemsBySession } = fm.rcCandidates({ names, live, rows });
    return fm.finishedSessions({ candidates, itemsBySession, inFlight: flight });
};
const n8 = (c) => 'rc-' + c.repeat(8);
let d = run({ names: [n8('a'), n8('b'), n8('c')], live: [lv('a'), lv('b'), lv('c')], rows: [wk(1, 'done', 'a'), wk(2, 'failed', 'b'), wk(3, 'cancelled', 'c')] });
assert.deepStrictEqual(d.close.map((x) => [x.id, x.itemId, x.state, x.tmuxSession]), [[FULL('a'), 1, 'done', n8('a')], [FULL('b'), 2, 'failed', n8('b')], [FULL('c'), 3, 'cancelled', n8('c')]]);
d = run({ names: [n8('a')], live: [lv('a', 'busy')], rows: [wk(1, 'done', 'a')] });
assert.ok(!d.close.length && d.keep[0].id === FULL('a'), 'busy status keeps it');
d = run({ names: [n8('a')], live: [lv('a')], rows: [wk(1, 'done', 'a')], flight: (sid) => sid === FULL('a') });
assert.ok(!d.close.length && /in flight/.test(d.keep[0].why), 'inFlight keeps it');
d = run({ names: [n8('a')], live: [lv('a')], rows: [wk(1, 'done', 'a'), wk(2, 'running', 'a')] });
assert.ok(!d.close.length && /item 2 is running/.test(d.keep[0].why), 'one open item keeps it');
d = run({ names: [n8('a')], live: [lv('a')], rows: [wk(1, 'failed', 'a'), wk(4, 'done', 'a')] });
assert.strictEqual(d.close[0].itemId, 4, 'the newest item is named');
d = run({ names: [n8('u')], live: [lv('u')] });
assert.deepStrictEqual(d, { close: [], keep: [], unowned: [{ id: FULL('u'), tmuxSession: n8('u') }] }, 'no item: unowned, never closed');
d = run({ names: [n8('u')] });
assert.deepStrictEqual(d.unowned, [{ id: null, tmuxSession: n8('u') }], 'no live process and no item: unowned');
d = run({ names: [n8('z')], rows: [wk(5, 'done', 'z')] });
assert.deepStrictEqual(d.close.map((x) => [x.id, x.itemId]), [[FULL('z'), 5]], 'tmux only (the CLI exited, the pane sleeps) with a done item: closed');
d = run({ names: [n8('z')], rows: [wk(5, 'done', 'z'), wk(6, 'running', 'z')] });
assert.ok(!d.close.length, 'tmux only with a running item: kept');
d = run({ names: [n8('y')], rows: [wk(7, 'done', 'y'), wk(8, 'done', 'y', 'yyyyyyyy-2222-4222-8222-222222222222')] });
assert.ok(!d.close.length && !d.unowned.length && /several sessions/.test(d.keep[0].why), 'two full ids under one id8: ambiguous, kept');
d = run({ names: [n8('a')], live: [lv('a')], rows: [wk(1, 'done', 'a'), wk(2, 'done', 'a', 'aaaaaaaa-2222-4222-8222-222222222222')] });
assert.strictEqual(d.close.length, 1, 'a live session settles the id8 even when old rows name another');
d = run({ names: [n8('h')], live: [lv('h')], rows: [wk(1, 'held', 'h')] });
assert.ok(!d.close.length, 'held is not terminal');
d = run({ names: ['rc-manual', 'main', 'rc-'], live: [], rows: [wk(1, 'done', 'a')] });
assert.deepStrictEqual(d.close, [], 'names that are not an id8 never match an item');
d = run({ names: [], live: [lv('o', 'idle', { origin: 'rc', tmuxSession: n8('o') }), lv('p', 'idle', { origin: 'tmux', tmuxSession: 'main' })], rows: [wk(1, 'done', 'o'), wk(2, 'done', 'p')] });
assert.deepStrictEqual(d.close.map((x) => x.id), [FULL('o')], 'older CLIs: a live origin rc session counts; other origins are ignored');
d = run({ names: [n8('o')], live: [lv('o', 'idle', { origin: 'rc', tmuxSession: n8('o') })], rows: [wk(1, 'done', 'o')] });
assert.strictEqual(d.close.length, 1, 'on the socket and origin rc: one candidate, not two');
// parkedSessions (#1256): a parked Input Required item's session closes when idle past the limit, never with work in flight
{
    const NOW = 10 * 3600e3; const LIM = 60 * 60000;
    const pk = (id, c, parkedAgo, state = 'input') => ({ id, state, session_id: FULL(c), parked_at: parkedAgo === null ? null : NOW - parkedAgo });
    const runP = ({ names, live = [], rows, flight = () => false, now = NOW }) => {
        const { candidates, itemsBySession } = fm.rcCandidates({ names, live, rows });
        return fm.parkedSessions({ candidates, itemsBySession, inFlight: flight, now, closeAfterMs: LIM });
    };
    let p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', LIM)] });
    assert.deepStrictEqual(p.close.map((x) => [x.id, x.itemId, x.parkedAt]), [[FULL('a'), 1, NOW - LIM]], 'idle and parked for the limit: closed');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', LIM - 1)] });
    assert.ok(!p.close.length && /less than/.test(p.keep[0].why), 'parked less than the limit ago: kept');
    p = runP({ names: [n8('a')], live: [lv('a', 'busy')], rows: [pk(1, 'a', 3 * LIM)] });
    assert.ok(!p.close.length && /in flight/.test(p.keep[0].why), 'a busy session is never closed');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM)], flight: (sid) => sid === FULL('a') });
    assert.ok(!p.close.length && /in flight/.test(p.keep[0].why), 'background work in flight keeps it');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM), pk(2, 'a', 0, 'running')] });
    assert.ok(!p.close.length && /item 2 is running/.test(p.keep[0].why), 'another item still working on the session keeps it');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM), pk(2, 'a', null, 'input')] });
    assert.ok(!p.close.length, 'an Input Required item that is not parked (a real question) keeps it');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM), pk(2, 'a', 5 * LIM, 'done'), pk(3, 'a', 2 * LIM)] });
    assert.deepStrictEqual(p.close.map((x) => x.itemId), [3], 'done items do not block; the newest park decides the age');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM), pk(2, 'a', LIM - 5)] });
    assert.ok(!p.close.length, 'the newest park is too recent');
    p = runP({ names: [n8('a')], live: [lv('a')], rows: [pk(1, 'a', 3 * LIM, 'done')] });
    assert.ok(!p.close.length && !p.keep.length, 'a finished item is finishedSessions\' business, not this decision\'s');
    p = runP({ names: ['rc-manual'], live: [], rows: [pk(1, 'a', 3 * LIM)] });
    assert.ok(!p.close.length, 'a tmux name that is not an id8 never matches');
    p = runP({ names: [n8('a')], live: [], rows: [pk(1, 'a', 3 * LIM)] });
    assert.strictEqual(p.close.length, 1, 'a tmux session whose claude process is gone closes the same way');
}
