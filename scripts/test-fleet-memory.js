const mi = (avail, sf, st) => `MemAvailable: ${avail * 1024} kB\nSwapTotal: ${st * 1024} kB\nSwapFree: ${sf * 1024} kB\n`;
assert.deepStrictEqual(fm.readMem(mi(2000, 5000, 16000)), { memAvailMb: 2000, swapFreeMb: 5000, swapTotalMb: 16000 });
assert.ok(fm.admission(fm.readMem(mi(2000, 5000, 16000))).ok);
