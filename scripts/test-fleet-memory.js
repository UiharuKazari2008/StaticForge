'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const fm = require('../modules/fleetMemory');
const mi = (avail, sf, st) => `MemAvailable: ${avail * 1024} kB\nSwapTotal: ${st * 1024} kB\nSwapFree: ${sf * 1024} kB\n`;
assert.deepStrictEqual(fm.readMem(mi(2000, 5000, 16000)), { memAvailMb: 2000, swapFreeMb: 5000, swapTotalMb: 16000 });
assert.ok(fm.admission(fm.readMem(mi(2000, 5000, 16000))).ok);
let a = fm.admission(fm.readMem(mi(900, 5000, 16000)));
assert.ok(!a.ok && /900 MB RAM/.test(a.reason));
a = fm.admission(fm.readMem(mi(4000, 399, 16265)));
assert.ok(!a.ok && /399 MB swap/.test(a.reason));
assert.ok(fm.admission(fm.readMem(mi(4000, 0, 0))).ok, 'no swap host: only RAM counts');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fm-test-'));
const pd = path.join(root, '-proj');
const dead = '11111111-1111-1111-1111-111111111111'; const live = '22222222-2222-2222-2222-222222222222'; const fresh = '33333333-3333-3333-3333-333333333333';
for (const id of [dead, live, fresh]) { fs.mkdirSync(path.join(pd, id, 'scratchpad'), { recursive: true }); fs.writeFileSync(path.join(pd, id, 'scratchpad', 'x'), 'x'.repeat(2048)); }
const old = new Date(Date.now() - 3 * 3600e3);
for (const id of [dead, live]) fs.utimesSync(path.join(pd, id), old, old);
const r = fm.sweepScratch({ root, live: new Set([live]) });
assert.strictEqual(r.removed, 1);
assert.ok(!fs.existsSync(path.join(pd, dead)) && fs.existsSync(path.join(pd, live)) && fs.existsSync(path.join(pd, fresh)));
fs.rmSync(root, { recursive: true });
assert.ok(fm.liveSessionIds().size > 0);
console.log('fleetMemory ok');
