#!/usr/bin/env node
// Desktop Background's photo galleries (Yukimi 2026-10-22): Japan, Europe, USA and fukapon (Flickr).
// Reads the curated list scripts/assets/wallpaper-galleries.json (each picture's gallery, group,
// download URL and credit), fetches each picture once, writes 1920px-wide WebP wallpapers and
// 184x138 thumbs to public/static_images/wallpapers/photos/<gallery>/(thumbs/), then
// public/scripts/comp/wallpaperGalleries.js (read by cplDesktopBackground.js) and CREDITS.md.
// Run: node scripts/build-wallpaper-galleries.js [--force]   (existing files are kept unless --force)
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const LIST = path.join(__dirname, 'assets', 'wallpaper-galleries.json');
const OUT_DIR = path.join(ROOT, 'public', 'static_images', 'wallpapers', 'photos');
const OUT_JS = path.join(ROOT, 'public', 'scripts', 'comp', 'wallpaperGalleries.js');
const WEB_DIR = '/static_images/wallpapers/photos';
const UA = 'StaticForgeWallpaperGalleries/1.0 (Dreamscape desktop backgrounds)';
const force = process.argv.includes('--force');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function download(url) {
    for (let attempt = 0; attempt < 6; attempt++) {
        const res = await fetch(url, { headers: { 'User-Agent': UA } });
        if (res.ok) return Buffer.from(await res.arrayBuffer());
        if (res.status !== 429 && res.status < 500) throw new Error(`${res.status} ${url}`);
        await sleep(5000 * (attempt + 1));
    }
    throw new Error(`gave up on ${url}`);
}

async function build(item) {
    const dir = path.join(OUT_DIR, item.gallery);
    const full = path.join(dir, `${item.file}.webp`);
    const thumb = path.join(dir, 'thumbs', `${item.file}.webp`);
    if (!force && fs.existsSync(full) && fs.existsSync(thumb)) return false;
    fs.mkdirSync(path.dirname(thumb), { recursive: true });
    const src = await download(item.download);
    await sharp(src).rotate().resize({ width: 1920, withoutEnlargement: true }).webp({ quality: 80 }).toFile(full);
    await sharp(src).rotate().resize(184, 138, { fit: 'cover' }).webp({ quality: 78 }).toFile(thumb);
    return true;
}

function writeData(list) {
    const galleries = list.galleries.map((g) => {
        const items = list.items.filter((i) => i.gallery === g.id && fs.existsSync(path.join(OUT_DIR, g.id, `${i.file}.webp`)));
        const groups = g.groups.filter((name) => items.some((i) => i.group === name));
        return {
            id: g.id,
            label: g.label,
            dir: `${WEB_DIR}/${g.id}`,
            groups,
            // f file, g group index, t title, a photographer, au their page, l license, lu its deed, s the original
            items: items.map((i) => ({
                f: i.file, g: groups.indexOf(i.group), t: i.title, a: i.author, au: i.authorUrl || '',
                l: i.license, lu: i.licenseUrl || '', s: i.source
            }))
        };
    });
    const body = galleries.map((g) => {
        const items = g.items.map((i) => `            ${JSON.stringify(i)}`).join(',\n');
        return `    {\n        id: ${JSON.stringify(g.id)},\n        label: ${JSON.stringify(g.label)},\n        dir: ${JSON.stringify(g.dir)},\n        groups: ${JSON.stringify(g.groups)},\n        items: [\n${items}\n        ]\n    }`;
    }).join(',\n');
    fs.writeFileSync(OUT_JS, `/**
 * Desktop Background's photo galleries (cplDesktopBackground.js Location ▾), with each photo's credit.
 * Generated by scripts/build-wallpaper-galleries.js from scripts/assets/wallpaper-galleries.json:
 * edit that list and rebuild, do not edit this file.
 */
(function (root) {
    'use strict';
    root.WALLPAPER_GALLERIES = [
${body}
    ];
    if (typeof module !== 'undefined' && module.exports) module.exports = root.WALLPAPER_GALLERIES;
})(typeof window !== 'undefined' ? window : globalThis);
`);
    const md = ['# Wallpaper photo credits', '',
        'Desktop Background\'s photo galleries. Every photo is used under the license named here; the',
        'files in this folder are resized copies of the originals linked below.', ''];
    for (const g of galleries) {
        md.push(`## ${g.label}`, '');
        for (const name of g.groups) {
            md.push(`### ${name}`, '');
            for (const i of g.items.filter((x) => g.groups[x.g] === name)) {
                md.push(`- \`${i.f}.webp\`: [${i.t || 'Untitled'}](${i.s}) by ${i.au ? `[${i.a}](${i.au})` : i.a || 'unknown'}, ${i.lu ? `[${i.l}](${i.lu})` : i.l}`);
            }
            md.push('');
        }
    }
    fs.writeFileSync(path.join(OUT_DIR, 'CREDITS.md'), md.join('\n'));
    return galleries;
}

(async () => {
    const list = JSON.parse(fs.readFileSync(LIST, 'utf8'));
    let made = 0;
    let failed = 0;
    for (const [n, item] of list.items.entries()) {
        try {
            if (await build(item)) {
                made++;
                await sleep(item.download.includes('wikimedia.org') ? 1500 : 400);
            }
        } catch (err) {
            failed++;
            console.warn(`skip ${item.gallery}/${item.file}: ${err.message}`);
        }
        if ((n + 1) % 25 === 0) console.log(`${n + 1}/${list.items.length}`);
    }
    const galleries = writeData(list);
    console.log(`wrote ${made} new, ${failed} failed; ${galleries.map((g) => `${g.id} ${g.items.length}`).join(', ')}`);
})();
