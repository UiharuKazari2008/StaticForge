function collectEnshutsukaMustAct(input) {
    const src = input && typeof input === 'object' && !Array.isArray(input) ? input : {};
    const forge = src.forge_data && typeof src.forge_data === 'object' ? src.forge_data : {};
    const dyn = src.dynamicGeneration || src.dynamic_generation || forge.dynamic_generation;
    const director = src.director;
    const sessionId = src.director_session_id || forge.director_session_id
        || (director && (director.sessionId || director.session_id));
    const messageId = src.director_message_id || forge.director_message_id
        || (director && (director.messageId || director.message_id));
    const prompt = director && (director.prompt || director.directive);
    const reasons = [];
    if (dynagenNeedsIntegration(dyn)) reasons.push('dynamicGeneration');
    if (sessionId || messageId || prompt
        || (director && typeof director === 'object' && !Array.isArray(director))) {
        reasons.push('director');
    }
    if (!reasons.length) return null;
    return {
        required: true,
        reasons,
        next: 'Bake dynamicGeneration.resolved into prompt/uc/characters (Director API is nooped). Then apply_studio_changes or generate_image with dynamicGeneration.integrated=true. Do not ignore this data.'
    };
}

const TRANSIENT_AGENT_PACKET_TYPES = new Set([
    'request_keep_alive',
    'image_generation_progress',
    'image_generation_intermediate',
    'dynamic_generation_progress_update',
    'generation_queued'
]);

function scoreAgentPacketReply(row) {
    if (!row || typeof row !== 'object') return -1;
    const type = String(row.type || '');
    if (TRANSIENT_AGENT_PACKET_TYPES.has(type)) return -1;
    if (type === 'error' || type.endsWith('_error')) return 3;
    if (type.endsWith('_response')) return 2;
    return 1;
}

function pickAgentPacketReply(replies) {
    const list = Array.isArray(replies) ? replies : [];
    let best = null;
    let bestScore = -1;
    for (let i = 0; i < list.length; i++) {
        const row = list[i];
        const score = scoreAgentPacketReply(row);
        if (score >= bestScore && score >= 0) {
            best = row;
            bestScore = score;
        }
    }
    return best;
}

