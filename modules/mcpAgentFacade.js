function collectMemoryNames(input) {
    const names = [];
    const seen = new Set();
    const push = (value) => {
        const name = String(value || '').trim();
        if (!name || seen.has(name)) return;
        seen.add(name);
        names.push(name);
    };
    push(input && input.name);
    if (Array.isArray(input && input.names)) input.names.forEach(push);
    else push(input && input.names);
    return names;
}

function runMemoryTool(globalResources, name, input) {
    name = canonMemoryTool(name);
    const db = resolveKnowledgeMemoryDb(globalResources);
    if (!db) {
        return { success: false, error: 'Knowledge memory database is not ready' };
    }
    if (name === 'list_memories') {
        const paged = db.listKnowledgeMemoriesPaged({
            limit: input.limit,
            offset: input.offset,
            search: input.search || '',
            category: input.category || null,
            model: input.model || null
        });
        return { success: true, ...paged };
    }
    if (name === 'search_memories') {
        const query = String(input.query || '').trim();
        if (!query) return { success: false, error: 'query is required' };
        return { success: true, results: db.searchKnowledgeMemories(query, input.category || null, input.model || null) };
    }
    if (name === 'get_memory') {
        const memoryNames = collectMemoryNames(input);
        if (!memoryNames.length) return { success: false, error: 'name or names is required' };
        const memories = [];
        const notFound = [];
        memoryNames.forEach((memoryName) => {
            const memory = db.getKnowledgeMemory(memoryName, true);
            if (memory) memories.push(memory);
            else notFound.push(memoryName);
        });
        if (!memories.length) {
            return { success: false, error: `Memory "${memoryNames.join(', ')}" not found`, notFound };
        }
        const needsRefinement = memories.some((memory) => Number(memory.confidence) < 0.6);
        return {
            success: true,
            memory: memories[0],
            memories,
            notFound: notFound.length ? notFound : undefined,
            needsRefinement,
            next: needsRefinement
                ? 'Confidence is below 60%. You MUST call save_memory or saveKnowledgeMemory on the same name (omit unchanged fields; confidence is a +0–0.25 bump). Grok Memory is not a write.'
                : undefined
        };
    }
    const memoryName = String(input.name || '').trim();
    if (!memoryName) {
        return { success: false, error: 'name is required' };
    }
    const existing = db.getKnowledgeMemory(memoryName, false);
    const description = input.description != null && String(input.description).trim()
        ? String(input.description).trim()
        : (existing && existing.description) || '';
    if (!description) {
        return { success: false, error: 'description is required when creating a memory' };
    }
    const refined = !!existing;
    const confidence = refined
        ? resolveRefinementConfidence(existing.confidence, input.confidence)
        : 0.1;
    const model = normalizeMemoryModel(input.model || (existing && existing.model));
    const saved = db.saveKnowledgeMemory(
        memoryName,
        description,
        input.category != null ? input.category : ((existing && existing.category) || 'mcp'),
        input.entities !== undefined ? input.entities : ((existing && existing.entities) || []),
        input.relations !== undefined ? input.relations : ((existing && existing.relations) || []),
        input.observations !== undefined ? input.observations : ((existing && existing.observations) || []),
        confidence,
        model
    );
    return {
        success: true,
        refined,
        previousConfidence: existing ? existing.confidence : null,
        confidence: saved.confidence,
        model: saved.model,
        needsRefinement: saved.confidence < 0.6,
        memory: saved
    };
}

